package net.frozenblock.wilderwild.mixin.block.chest;

import net.frozenblock.wilderwild.block.impl.ChestUtil;
import net.minecraft.core.BlockPos;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.entity.BlockEntity;
import net.minecraft.world.level.block.entity.ChestBlockEntity;
import net.minecraft.world.level.block.state.BlockState;
import org.jspecify.annotations.Nullable;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(BlockEntity.class)
public class BlockEntityMixin {

	@Shadow
	@Nullable
	protected Level level;

	@Inject(method = "preRemoveSideEffects", at = @At("HEAD"))
	public void wilderWild$bubbleBurstOnChestRemove(BlockPos pos, BlockState state, CallbackInfo info) {
		if (this.level == null) return;
		if (!(BlockEntity.class.cast(this) instanceof ChestBlockEntity chest)) return;
		ChestUtil.bubbleBurst(this.level, pos, state, chest);
	}
}
